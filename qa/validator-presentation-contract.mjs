import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context={window:{}};
vm.runInNewContext(fs.readFileSync('modules/control-auto/validator-presentation.js','utf8'),context);
const model=context.window.RYM_VALIDATOR_PRESENTATION;
const source=JSON.parse(fs.readFileSync('qa/fixtures/validator-gps-official.json','utf8'));
let combinations=0;
for(const installed1 of [false,true])for(const installed2 of [false,true])for(const ok1 of [false,true])for(const ok2 of [false,true]){
  if((!installed1&&ok1)||(!installed2&&ok2))continue;
  const scope={inst:Number(installed1)+Number(installed2),rep:Number(ok1)+Number(ok2),historical:false,oper:'ACTIVO'};
  vm.runInNewContext(source.adminClassification+';result={level,reason};',scope);
  const row={gps1:{installed:installed1,ok:ok1},gps2:{installed:installed2,ok:ok2},nivel:'OK'};
  const label={OK:'NORMAL',ALERTA:'ALERTA',CRITICO:'CRÍTICO'}[scope.result.level];
  assert.equal(model.gps(row).level,label,'Official GPS classification mismatch '+JSON.stringify(row));
  combinations++;
}
assert.equal(model.gps(null).level,'SIN INFORMACIÓN');
assert.equal(model.gps({nivel:'HISTORICO'}).level,'SIN INFORMACIÓN');
assert.equal(model.gps({nivel:'OK',estatus_control:'CERRADA'}).level,'SIN INFORMACIÓN');
assert.equal(model.gps({nivel:'NO CRITICO'}).level,'SIN INFORMACIÓN','Text substring must not classify an unknown level');
assert.equal(model.gps({gps1:{installed:false,ok:false},gps2:{installed:true,ok:true},nivel:'ALERTA'}).level,'NORMAL');
const counterexample={inst:1,rep:1,s1:{installed:false,ok:false},s2:{installed:true,ok:true}};
vm.runInNewContext(source.validatorClassification+';result={level,reason};',counterexample);
assert.equal(counterexample.result.level,'ALERTA','Audited Validator endpoint discrepancy changed');
assert.equal(model.gps({gps1:counterexample.s1,gps2:counterexample.s2,nivel:counterexample.result.level,razon:counterexample.result.reason}).level,'NORMAL');
assert.equal(model.revisado({estado:'PENDIENTE',meses_atraso:3},{},'VIGENTE'),'VENCIDO');
assert.equal(model.revisado({estado:'PENDIENTE',meses_atraso:0},{estado_revisado:'VIGENTE'}),'PENDIENTE');
assert.equal(model.revisado({estado:'VIGENTE'},{},'VENCIDO'),'VIGENTE');
assert.equal(model.revisado({}, {estado_revisado:'VENCIDO'}),'VENCIDO');
assert.equal(model.revisado({estado:'SIN_MES'}),'SIN MES');
assert.equal(model.compare(' ab-12 34 ','AB1234'),'match');
assert.equal(model.compare('AB1234','AB1235'),'diff');
assert.equal(model.compare(null,'VIN-LARGO'),'missing');
assert.equal(model.compare('—','CHASIS'),'missing');
assert.equal(model.balance('B/. 1,234.56'),1234.56);
assert.equal(model.balance('-2.00'),-2);
assert.equal(model.balance('0.25'),.25);
assert.ok(Number.isNaN(model.balance('No disponible')),'Missing balance must not become zero');
assert.ok(Number.isNaN(model.balance('')));
console.log(`PASS: ${combinations} GPS combinations against gps-rym-admin v${source.adminVersion}; real pending/expired states and identity normalization.`);
